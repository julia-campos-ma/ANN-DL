"""
Step 5 -- the ONLY script that evaluates on the test set.

The configuration chosen in Step 4 (results/step4.json) is retrained with 5 seeds, each
with early stopping on validation and its own cost-based threshold set on validation. The
baselines of Step 1 (same hyperparameters, same final feature set) are refitted and
evaluated in the same table. Prints the success check of Step 0. Figures 6 and 7.

Writes results/step5.json and, for Step 6, results/test_predictions.npz and
results/mlp_seed42.pt (both ignored by git; regenerated by this script).

Run from the repository root (about 3 minutes):
    python docs/projects/classification/code/step5_test.py
"""

import numpy as np
import pandas as pd
import torch
from sklearn.dummy import DummyClassifier
from sklearn.metrics import confusion_matrix, precision_recall_curve, roc_curve

import common
import model as M
from common import SEEDS, section
from step1_baselines import fit_boosting, fit_logistic

plt = common.style()

KEYS = ["average_precision", "roc_auc", "macro_f1", "f1_1", "precision_1", "recall_1",
        "f1_0", "precision_0", "recall_0", "accuracy", "cost", "brier", "threshold"]


def evaluate(name, p_val, p_test, d):
    t, _ = common.cost_threshold(d["y_val"], p_val)
    return {"model": name, **common.metrics(d["y_test"], p_test, t),
            "val_ap": common.metrics(d["y_val"], p_val, t)["average_precision"]}


def main():
    s4 = common.load_json("step4.json")
    s1 = common.load_json("step1.json")
    cfg = s4["chosen"]
    drop = tuple(cfg["drop"])
    d = common.prepare(drop, with_test=True)
    Xf, yf, Xv, yv, Xt, yt = d["X_fit"], d["y_fit"], d["X_val"], d["y_val"], d["X_test"], d["y_test"]
    pw = 1.0 if cfg["pos_weight"] == "1" else float((1 - yf).sum() / yf.sum())
    hidden = tuple(cfg["hidden"])

    section("Chosen configuration (from Step 4) and data")
    print(cfg, f"pos_weight = {pw:.3f}")
    print(f"inputs {Xf.shape[1]}; train {len(yf)}, validation {len(yv)}, test {len(yt)} rows; "
          f"test prevalence {yt.mean():.4f}")

    rows, preds = [], {}
    section(f"Network: {len(SEEDS)} seeds, early stopping on validation, threshold on validation")
    for seed in SEEDS:
        net, h = M.train_model(Xf, yf, Xv, yv, hidden=hidden, dropout=cfg["dropout"],
                               weight_decay=cfg["weight_decay"], lr=cfg["lr"], batch_size=cfg["batch_size"],
                               pos_weight=pw, seed=seed)
        pv, pt = M.predict_proba(net, Xv), M.predict_proba(net, Xt)
        r = evaluate("MLP", pv, pt, d)
        r.update(seed=seed, best_epoch=h["best_epoch"], stopped=h["stopped_epoch"], params=M.n_params(net))
        rows.append(r)
        preds[f"mlp_{seed}"] = pt.astype(np.float32)
        preds[f"mlp_val_{seed}"] = pv.astype(np.float32)
        if seed == SEEDS[0]:
            torch.save(net.state_dict(), common.RESULTS / "mlp_seed42.pt")
        print(f"seed {seed}: best epoch {h['best_epoch']} (stopped {h['stopped_epoch']})  threshold {r['threshold']:.2f}  "
              f"test AP {r['average_precision']:.4f}  ROC-AUC {r['roc_auc']:.4f}  macro F1 {r['macro_f1']:.4f}")

    section("Baselines refitted on the same features")
    dummy = DummyClassifier(strategy="most_frequent").fit(Xf, yf)
    r = {"model": "trivial", **common.metrics(yt, dummy.predict_proba(Xt)[:, 1], 0.5), "seed": None}
    rows.append(r)
    lr = fit_logistic(Xf, yf, s1["logistic"]["C"])
    pt = lr.predict_proba(Xt)[:, 1]
    preds["logistic"] = pt.astype(np.float32)
    rows.append({**evaluate("logistic", lr.predict_proba(Xv)[:, 1], pt, d), "seed": None})
    b = s1["boosting"]
    for seed in SEEDS:
        hgb = fit_boosting(Xf, yf, b["learning_rate"], b["max_leaf_nodes"], b["max_iter"], seed=seed)
        pt = hgb.predict_proba(Xt)[:, 1]
        preds[f"boosting_{seed}"] = pt.astype(np.float32)
        rows.append({**evaluate("boosting", hgb.predict_proba(Xv)[:, 1], pt, d), "seed": seed})

    df = pd.DataFrame(rows)
    summary = df.groupby("model", sort=False)[KEYS].agg(["mean", "std"]).fillna(0.0)
    section("Table -- test metrics, mean ± std over seeds (logistic and trivial are deterministic)")
    with pd.option_context("display.width", 250):
        print(summary.round(4).to_string())

    section("Success criterion (Step 0)")
    mlp_ap = df.loc[df.model == "MLP", "average_precision"]
    lin_ap = float(df.loc[df.model == "logistic", "average_precision"].iloc[0])
    hgb_ap = df.loc[df.model == "boosting", "average_precision"]
    gain = mlp_ap.mean() - lin_ap
    met = bool(gain >= common.MIN_GAIN_OVER_LINEAR and gain > 2 * mlp_ap.std(ddof=1))
    print(f"MLP test AP {mlp_ap.mean():.4f} ± {mlp_ap.std(ddof=1):.4f}; logistic {lin_ap:.4f}; "
          f"gain {gain:+.4f} (needs >= {common.MIN_GAIN_OVER_LINEAR} and > 2 std = {2 * mlp_ap.std(ddof=1):.4f}) "
          f"-> {'MET' if met else 'NOT MET'}")
    print(f"MLP − boosting: {mlp_ap.mean() - hgb_ap.mean():+.4f}  (boosting {hgb_ap.mean():.4f} ± {hgb_ap.std(ddof=1):.4f})")
    print(f"ensemble of the 5 MLP seeds (mean probability), for reference: AP "
          f"{common.metrics(yt, np.mean([preds[f'mlp_{s}'] for s in SEEDS], 0), 0.5)['average_precision']:.4f}")

    # Confusion matrix of the seed-42 network
    r42 = df[(df.model == "MLP") & (df.seed == SEEDS[0])].iloc[0]
    cm = confusion_matrix(yt, preds[f"mlp_{SEEDS[0]}"] >= r42["threshold"], labels=[0, 1])
    print(f"\nconfusion matrix, MLP seed {SEEDS[0]} at threshold {r42['threshold']:.2f} (rows = true, cols = predicted):")
    print(cm)
    cms = np.array([[df[df.model == "MLP"][k].mean() for k in ("tn", "fp")],
                    [df[df.model == "MLP"][k].mean() for k in ("fn", "tp")]])
    print("mean over the 5 seeds:\n", cms.round(1))

    # Figure 6 -- confusion matrix (seed 42) and per-class metrics
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(9, 3.6), gridspec_kw={"width_ratios": [1, 1.25]})
    im = a1.imshow(cm, cmap="Blues")
    for i in range(2):
        for j in range(2):
            a1.text(j, i, f"{cm[i, j]:,}".replace(",", ".") + f"\n({cm[i, j] / cm[i].sum():.1%})".replace(".", ","),
                    ha="center", va="center", color="white" if cm[i, j] > cm.max() / 2 else "black")
    a1.set_xticks([0, 1], ["não cancela", "cancela"])
    a1.set_yticks([0, 1], ["não cancelou", "cancelou"])
    a1.set_xlabel("previsto")
    a1.set_ylabel("real")
    a1.grid(False)
    a1.set_title(f"Matriz de confusão (semente 42, limiar {r42['threshold']:.2f})".replace(".", ","))
    fig.colorbar(im, ax=a1, fraction=0.046)
    models = ["logistic", "boosting", "MLP"]
    names = {"logistic": "logística", "boosting": "boosting", "MLP": "MLP"}
    metrics_plot = [("precision_0", "precisão\nnão cancela"), ("recall_0", "recall\nnão cancela"),
                    ("precision_1", "precisão\ncancela"), ("recall_1", "recall\ncancela"),
                    ("macro_f1", "F1\nmacro")]
    x = np.arange(len(metrics_plot))
    for k, m in enumerate(models):
        means = [summary.loc[m, (key, "mean")] for key, _ in metrics_plot]
        stds = [summary.loc[m, (key, "std")] for key, _ in metrics_plot]
        a2.bar(x + (k - 1) * 0.27, means, 0.27, yerr=stds, capsize=2, label=names[m],
               color=common.MODEL_COLORS[m.lower()])
    a2.set_xticks(x, [lab for _, lab in metrics_plot])
    a2.set_ylim(0.4, 1.0)
    a2.set_ylabel("valor no teste (média ± dp)")
    a2.set_title("Métricas por classe no limiar de custo")
    a2.legend(ncol=3, loc="upper center")
    fig.suptitle("Figura 6 — Avaliação no teste: matriz de confusão da MLP e métricas por classe",
                 fontweight="bold", fontsize=10)
    fig.tight_layout()
    fig.savefig(common.FIGURES / "fig06-test-confusion.png")
    plt.close(fig)

    # Figure 7 -- PR and ROC curves
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(9, 3.8))
    curves = {"MLP (semente 42)": (preds[f"mlp_{SEEDS[0]}"], common.MODEL_COLORS["mlp"]),
              "boosting (semente 42)": (preds[f"boosting_{SEEDS[0]}"], common.MODEL_COLORS["boosting"]),
              "logística": (preds["logistic"], common.MODEL_COLORS["logistic"])}
    for name, (p, c) in curves.items():
        pr, rc, _ = precision_recall_curve(yt, p)
        fpr, tpr, _ = roc_curve(yt, p)
        m = common.metrics(yt, p, 0.5)
        a1.plot(rc, pr, color=c, lw=1.4, label=f"{name}: AP {m['average_precision']:.3f}".replace(".", ","))
        a2.plot(fpr, tpr, color=c, lw=1.4, label=f"{name}: AUC {m['roc_auc']:.3f}".replace(".", ","))
    a1.axhline(yt.mean(), color="#888888", ls="--", lw=1, label=f"trivial: AP {yt.mean():.3f}".replace(".", ","))
    pt42 = preds[f"mlp_{SEEDS[0]}"] >= r42["threshold"]
    a1.scatter([r42["recall_1"]], [r42["precision_1"]], color="black", zorder=5, s=30,
               label=f"limiar de custo ({r42['threshold']:.2f})".replace(".", ","))
    a2.plot([0, 1], [0, 1], color="#888888", ls="--", lw=1, label="trivial: AUC 0,500")
    fpr42 = (pt42 & (yt == 0)).sum() / (yt == 0).sum()
    a2.scatter([fpr42], [r42["recall_1"]], color="black", zorder=5, s=30)
    a1.set_xlabel("recall (cancela)")
    a1.set_ylabel("precisão (cancela)")
    a1.set_title("Curva precisão–recall (teste)")
    a1.set_ylim(0.3, 1.02)
    a1.legend(loc="lower left")
    a2.set_xlabel("taxa de falsos positivos")
    a2.set_ylabel("taxa de verdadeiros positivos (recall)")
    a2.set_title("Curva ROC (teste)")
    a2.legend(loc="lower right")
    fig.suptitle("Figura 7 — Curvas PR e ROC no teste: MLP × baselines", fontweight="bold", fontsize=10)
    fig.tight_layout()
    fig.savefig(common.FIGURES / "fig07-test-curves.png")
    plt.close(fig)

    np.savez_compressed(common.RESULTS / "test_predictions.npz", y_test=yt, y_val=yv, **preds)
    common.save_json("step5.json", {
        "config": cfg, "pos_weight": pw, "rows": df.to_dict(orient="records"),
        "summary": [{"model": m, **{f"{k} {s}": float(summary.loc[m, (k, s)]) for k, s in summary.columns}}
                    for m in summary.index],
        "criterion": {"mlp_ap_mean": float(mlp_ap.mean()), "mlp_ap_std": float(mlp_ap.std(ddof=1)),
                      "logistic_ap": lin_ap, "gain": float(gain), "met": met,
                      "boosting_ap_mean": float(hgb_ap.mean()), "boosting_ap_std": float(hgb_ap.std(ddof=1))},
        "confusion_seed42": cm.tolist(), "confusion_mean": cms.tolist(),
    })


if __name__ == "__main__":
    main()
